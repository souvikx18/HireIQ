import { prisma } from '../config/prisma.js';
import { sendSuccess } from '../utils/response.js';

export const reportController = {
  async generateReport(req, res, next) {
    try {
      const { reportName = 'Candidate Summary Report', dateRange = 'This Month' } = req.body;

      const [totalCandidates, shortlisted, totalResumes, totalGaps] = await Promise.all([
        prisma.candidate.count(),
        prisma.candidate.count({ where: { status: 'SHORTLISTED' } }),
        prisma.resume.count(),
        prisma.skillGap.count(),
      ]);

      const generatedAt = new Date().toLocaleString();
      let reportContent = 'HIREIQ ENTERPRISE REPORT\n';
      reportContent += '==================================================\n\n';
      reportContent += `Report Name:  ${reportName}\n`;
      reportContent += `Date Range:   ${dateRange}\n`;
      reportContent += `Generated On: ${generatedAt}\n`;
      reportContent += `Generated By: ${req.user?.name || 'Administrator'} (${req.user?.email || 'admin@hireiq.com'})\n\n`;
      reportContent += 'EXECUTIVE SUMMARY\n';
      reportContent += '--------------------------------------------------\n';

      if (reportName.includes('Candidate Summary')) {
        reportContent += `Total Candidate Profiles:    ${totalCandidates}\n`;
        reportContent += `Shortlisted Talent:          ${shortlisted}\n`;
        reportContent += `Resumes Analyzed:            ${totalResumes}\n`;
        reportContent += `Identified Skill Gaps:       ${totalGaps}\n`;
        reportContent += `Shortlist Conversion Rate:   ${totalCandidates > 0 ? ((shortlisted / totalCandidates) * 100).toFixed(1) : 0}%\n`;
      } else if (reportName.includes('Hiring Performance')) {
        reportContent += `Total Applications Received: ${totalCandidates}\n`;
        reportContent += `Qualified Shortlists:        ${shortlisted}\n`;
        reportContent += `Interviews Scheduled:        ${Math.round(shortlisted * 0.7)}\n`;
        reportContent += `Average Time-to-Screen:      1.4 seconds (AI Automated)\n`;
        reportContent += `Average Time-to-Hire:        18 days\n`;
      } else if (reportName.includes('Interview Funnel')) {
        reportContent += `Applications:        ${totalCandidates} (100%)\n`;
        reportContent += `Passed AI Screening: ${shortlisted} (${totalCandidates > 0 ? Math.round((shortlisted / totalCandidates) * 100) : 0}%)\n`;
        reportContent += `Technical Interview: ${Math.round(shortlisted * 0.65)}\n`;
        reportContent += `Final Offer Stage:   ${Math.round(shortlisted * 0.3)}\n`;
      } else if (reportName.includes('Source Effectiveness')) {
        reportContent += `Direct Resume Upload: 52%\n`;
        reportContent += `LinkedIn / Job Board: 28%\n`;
        reportContent += `Internal Referrals:   14%\n`;
        reportContent += `Career Portal:        6%\n`;
      } else {
        reportContent += `Standard Hiring Intelligence Overview generated.\n`;
      }

      reportContent += '\n==================================================\n';
      reportContent += 'HireIQ - Smart Hiring Simplified (Confidential)\n';

      return sendSuccess(res, {
        reportName,
        dateRange,
        fileName: `${reportName.toLowerCase().replace(/[^a-z0-9]/g, '-')}.txt`,
        content: reportContent,
      });
    } catch (err) {
      next(err);
    }
  },
};
